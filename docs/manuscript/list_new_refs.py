#!/usr/bin/env python3
"""Write new_refs_to_verify.md: every references.bib entry added (or changed) since a base commit, with key,
authors, title, venue, year and DOI as they stand in the bib. Entries are listed, never modified.
Usage: python3 list_new_refs.py [base_commit]   (default d0f87cc)"""
import os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); BASE = sys.argv[1] if len(sys.argv) > 1 else 'd0f87cc'


def entries(text):
    out = {}
    for m in re.finditer(r'@(\w+)\{([^,\s]+),(.*?)\n\}', text, re.S):
        body = m.group(3); f = {}
        for fm in re.finditer(r'(\w+)\s*=\s*\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}', body): f[fm.group(1).lower()] = ' '.join(fm.group(2).split())
        out[m.group(2)] = (m.group(1).lower(), f, ' '.join(body.split()))
    return out


old = entries(subprocess.run(['git', 'show', f'{BASE}:docs/manuscript/references.bib'], cwd=HERE, capture_output=True, text=True, check=True).stdout)
new = entries(open(os.path.join(HERE, 'references.bib')).read())
cited = set(k.strip() for c in re.findall(r'\\cite\{([^}]*)\}', open(os.path.join(HERE, 'main.tex')).read()) for k in c.split(','))
added = [k for k in new if k not in old]; changed = [k for k in new if k in old and new[k][2] != old[k][2]]
clean = lambda s: re.sub(r'[{}]', '', s).replace('\\"e', 'ë').replace("\\'e", 'é').replace("\\'o", 'ó').replace('\\"O', 'Ö').replace('\\"o', 'ö').replace("\\'", '')
row = lambda k: (lambda t, f: f"| `{k}` | {clean(f.get('author', ''))} | {clean(f.get('title', ''))} | {clean(f.get('journal', f.get('booktitle', '')))} | {f.get('year', '')} | {f.get('doi', '')} | {'yes' if k in cited else 'no'} |")(*new[k][:2])
hdr = '| key | authors | title | venue | year | DOI | cited in main.tex |\n|---|---|---|---|---|---|---|'
md = [f'# References added or changed since {BASE}', '',
      f'Generated by `list_new_refs.py` from `references.bib` against commit `{BASE}`. Entries are listed exactly as they stand; '
      'none is modified here. Verify each against its DOI record before submission.', '',
      f'## Added ({len(added)})', '', hdr] + [row(k) for k in added] + ['', f'## Replaced or edited ({len(changed)})', '', hdr] + [row(k) for k in changed] + ['']
open(os.path.join(HERE, 'new_refs_to_verify.md'), 'w').write('\n'.join(md)); print(f'{len(added)} added, {len(changed)} changed')
